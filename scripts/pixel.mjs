// Tiny pixel-art helpers: sprites from strings, and a 3x5 pixel font.

// Draw a sprite. rows: strings, one char per pixel; "." is empty.
// colors: { char: "#hex" }. Runs of the same colour on a row become one rect.
export function sprite(rows, colors, x, y, u, extra = "") {
  let out = "";
  rows.forEach((row, j) => {
    let i = 0;
    while (i < row.length) {
      const c = row[i];
      if (c === "." || c === " " || !colors[c]) { i++; continue; }
      let k = i;
      while (k < row.length && row[k] === c) k++;
      out += `<rect x="${(x + i) * u}" y="${(y + j) * u}" width="${(k - i) * u}" height="${u}" fill="${colors[c]}"${extra}/>`;
      i = k;
    }
  });
  return out;
}

